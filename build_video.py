#!/usr/bin/env python3
"""
build_video.py
Full 1080p Documentary Video Builder:
- Takes scenes.json (generated by generate_audio.py)
- Processes images with cinematic Ken Burns camera motion & color grade
- Processes title cards and video clips
- Concatenates video segments at 1080p 30fps
- Muxes with mastered soundtrack (Christopher Neural TTS + Ducked Cinematic BGM)
- Supports fast parallel or sequential rendering
"""

import os, sys, json, subprocess
from concurrent.futures import ThreadPoolExecutor

PROJECT_DIR = os.path.dirname(os.path.abspath(__file__))
TEMP_SEGMENTS_DIR = os.path.join(PROJECT_DIR, "output/segments")
OUTPUT_DIR = os.path.join(PROJECT_DIR, "output")
os.makedirs(TEMP_SEGMENTS_DIR, exist_ok=True)
os.makedirs(OUTPUT_DIR, exist_ok=True)

def run(cmd):
    subprocess.run(cmd, shell=True, check=True)

def render_scene_clip(scene):
    sid = scene["id"]
    stype = scene["type"]
    dur = float(scene["duration"])
    asset_rel = scene["asset"]
    asset_path = os.path.join(PROJECT_DIR, asset_rel)
    out_clip = os.path.join(TEMP_SEGMENTS_DIR, f"{sid}.mp4")
    
    # Check if already rendered
    if os.path.exists(out_clip) and os.path.getsize(out_clip) > 1000:
        return out_clip

    # 1. Title Card
    if stype == "title_card":
        cmd = (
            f'ffmpeg -y -i "{asset_path}" -t {dur} '
            f'-vf "fps=30,scale=1920:1080:force_original_aspect_ratio=decrease,pad=1920:1080:(ow-iw)/2:(oh-ih)/2" '
            f'-c:v libx264 -preset fast -pix_fmt yuv420p -an "{out_clip}"'
        )
        run(cmd)
        return out_clip

    # 2. Video Footage Clip
    elif stype == "video":
        cmd = (
            f'ffmpeg -y -stream_loop -1 -i "{asset_path}" -t {dur} '
            f'-vf "scale=1920:1080:force_original_aspect_ratio=increase,crop=1920:1080,fps=30,eq=contrast=1.05:saturation=1.05" '
            f'-c:v libx264 -preset fast -pix_fmt yuv420p -an "{out_clip}"'
        )
        run(cmd)
        return out_clip

    # 3. Image with Ken Burns camera motion
    elif stype == "image":
        motion = scene.get("motion", "zoom_in")
        num_frames = max(30, int(dur * 30))
        
        # Ken Burns expressions (optimized for performance & elegance)
        if motion == "zoom_in":
            zp = f"zoompan=z='min(zoom+0.0012,1.15)':d={num_frames}:x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':s=1920x1080:fps=30"
        elif motion == "zoom_out":
            zp = f"zoompan=z='if(lte(zoom,1.0),1.15,max(1.001,zoom-0.0012))':d={num_frames}:x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':s=1920x1080:fps=30"
        elif motion == "pan_left":
            zp = f"zoompan=z=1.12:d={num_frames}:x='(1.0-on/{num_frames})*(iw-iw/zoom)':y='ih/2-(ih/zoom/2)':s=1920x1080:fps=30"
        elif motion == "pan_right":
            zp = f"zoompan=z=1.12:d={num_frames}:x='(on/{num_frames})*(iw-iw/zoom)':y='ih/2-(ih/zoom/2)':s=1920x1080:fps=30"
        elif motion == "pan_up":
            zp = f"zoompan=z=1.12:d={num_frames}:x='iw/2-(iw/zoom/2)':y='(1.0-on/{num_frames})*(ih-ih/zoom)':s=1920x1080:fps=30"
        elif motion == "pan_down":
            zp = f"zoompan=z=1.12:d={num_frames}:x='iw/2-(iw/zoom/2)':y='(on/{num_frames})*(ih-ih/zoom)':s=1920x1080:fps=30"
        else:
            zp = f"zoompan=z='min(zoom+0.0008,1.10)':d={num_frames}:x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':s=1920x1080:fps=30"

        # Image processing: input is 2560x1440 16:9 QHD, so zoompan operates on perfect 16:9 without any stretching!
        filter_str = f"{zp},cas=strength=0.45,eq=contrast=1.05:brightness=-0.01:saturation=1.04"
        
        cmd = (
            f'ffmpeg -y -loop 1 -i "{asset_path}" -t {dur} '
            f'-vf "{filter_str}" -c:v libx264 -preset fast -pix_fmt yuv420p -an "{out_clip}"'
        )
        run(cmd)
        return out_clip

    else:
        raise ValueError(f"Unknown scene type: {stype}")

def build_full_video(manifest_file, audio_file, output_file):
    if not os.path.isabs(manifest_file):
        manifest_file = os.path.join(PROJECT_DIR, manifest_file)
    if not os.path.isabs(audio_file):
        audio_file = os.path.join(PROJECT_DIR, audio_file)
    if not os.path.isabs(output_file):
        output_file = os.path.join(PROJECT_DIR, output_file)
        
    print(f"=== Reading Manifest: {manifest_file} ===")
    with open(manifest_file, "r") as f:
        scenes = json.load(f)
        
    print(f"Found {len(scenes)} scenes to assemble.")
    
    # Render scene clips (using 4 worker threads for fast speed)
    print("=== Rendering Scene Clips with Ken Burns Motion & Cutaways ===")
    with ThreadPoolExecutor(max_workers=4) as executor:
        results = list(executor.map(render_scene_clip, scenes))
        
    print("All scene clips rendered successfully!")
    
    # Create concat file
    concat_txt = os.path.join(TEMP_SEGMENTS_DIR, "video_concat.txt")
    with open(concat_txt, "w") as f:
        for clip in results:
            f.write(f"file '{clip}'\n")
            
    # Concatenate all visual clips into a continuous raw video
    temp_raw_video = os.path.join(OUTPUT_DIR, "temp_raw_video.mp4")
    print("=== Concatenating Video Clips ===")
    run(f'ffmpeg -y -f concat -safe 0 -i "{concat_txt}" -c copy "{temp_raw_video}"')
    
    # Mux with the mastered soundtrack
    print(f"=== Muxing with Mastered Audio: {audio_file} ===")
    run(
        f'ffmpeg -y -i "{temp_raw_video}" -i "{audio_file}" '
        f'-c:v copy -c:a aac -b:a 256k -movflags +faststart -shortest "{output_file}"'
    )
    
    # Clean up temp raw video
    if os.path.exists(temp_raw_video):
        os.remove(temp_raw_video)
        
    print(f"\n🎉 FULL DOCUMENTARY VIDEO COMPLETE!")
    print(f"Output File: {output_file}")
    print(f"File Size: {os.path.getsize(output_file) / (1024*1024):.2f} MB")

def main():
    manifest_path = os.path.join(PROJECT_DIR, "scenes.json")
    audio_path = os.path.join(PROJECT_DIR, "assets/audio/voiceover_with_bgm.mp3") if os.path.exists(os.path.join(PROJECT_DIR, "assets/audio/voiceover_with_bgm.mp3")) else os.path.join(PROJECT_DIR, "assets/audio/voiceover_with_bgm.wav")
    final_output = os.path.join(OUTPUT_DIR, "trump_end_documentary_1080p.mp4")
    
    if len(sys.argv) > 1:
        manifest_path = sys.argv[1]
    if len(sys.argv) > 2:
        audio_path = sys.argv[2]
    if len(sys.argv) > 3:
        final_output = sys.argv[3]
        
    build_full_video(manifest_path, audio_path, final_output)

if __name__ == "__main__":
    main()
