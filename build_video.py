#!/usr/bin/env python3
"""
build_video.py
Full 1080p Documentary Video Builder:
- Takes scenes.json (generated by generate_audio.py)
- Smooth OpenCV Sub-pixel Ken Burns Camera Motion (Zero Jitter / Zero Shaking)
- Cosine S-curve Easing for cinematic organic camera acceleration and deceleration
- Processes title cards and video clips
- Concatenates video segments at 1080p 30fps
- Muxes with mastered soundtrack (Christopher Neural TTS + Ducked Cinematic BGM)
- Supports fast parallel multi-threaded rendering
"""

import os, sys, json, math, subprocess
from concurrent.futures import ThreadPoolExecutor

PROJECT_DIR = os.path.dirname(os.path.abspath(__file__))

